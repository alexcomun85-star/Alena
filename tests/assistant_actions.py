"""Run against the local preview before releasing assistant actions."""
from pathlib import Path
import subprocess,json
from urllib.parse import urlparse,parse_qs
from playwright.sync_api import sync_playwright, expect
Path("qa-output").mkdir(exist_ok=True)
with sync_playwright() as p:
    browser=p.chromium.launch()
    page=browser.new_page()
    errors=[]
    def gateway(route):
        url=urlparse(route.request.url)
        query=parse_qs(url.query).get('q',[''])[0]
        if url.path.endswith('/recipes'):
            rows=[{'id':'wiki-test','title':'Чечевичный суп из открытого источника','ingredients':['Чечевица — 100 г','Морковь — 1 шт.'],'steps':['Промойте чечевицу и сварите согласно упаковке.','Добавьте морковь и доведите до готовности.'],'source':'Викиучебник','url':'https://ru.wikibooks.org/wiki/Рецепт:Тест','license':'CC BY-SA'}] if 'чечевица' in query else []
            data={'recipes':rows}
        else:
            data={'foods':[{'name':'Тестовый продукт из интернета','brand':'Тест','unit':'г','k':100,'p':10,'f':4,'c':6,'url':'https://perek.us/food/test','source':'perek.us'}]}
        route.fulfill(status=200,headers={'Access-Control-Allow-Origin':'*'},content_type='application/json',body=json.dumps(data,ensure_ascii=False))
    page.route('https://alenafit-food-api.honeycivet19.chatgpt.site/api/**',gateway)
    page.on('pageerror',lambda e: errors.append(str(e)))
    for width in (320,390,768,1280):
        page.set_viewport_size({'width':width,'height':844})
        page.goto('http://localhost:8766/assistant-tools.html')
        page.get_by_role('button',name='Продукты и калории',exact=True).click()
        page.locator('#search').fill('яблоко')
        page.locator('#grams').fill('200')
        expect(page.locator('#food-results')).to_contain_text('104 ккал')
        page.get_by_text('Включить в итог',exact=True).first.click()
        page.locator('#grams').fill('-1')
        expect(page.locator('#food-results')).to_contain_text('от 1 до 3000')
        page.get_by_role('button',name='Что приготовить',exact=True).click()
        expect(page.locator('.starter').filter(has_text='Макароны и сосиски')).to_be_visible()
        page.locator('#ingredients').fill('макароны сосиски кетчуп майонез')
        page.get_by_role('button',name='Подобрать блюда',exact=True).click()
        expect(page.locator('#recipe-results')).to_contain_text('Макароны с сосисками')
        expect(page.locator('#recipe-results')).to_contain_text('МОЖНО ПРИГОТОВИТЬ СЕЙЧАС')
        expect(page.locator('#recipe-results .recipe h2').first).to_be_in_viewport()
        page.screenshot(path='qa-output/afita-pantry-'+str(width)+'.png',full_page=True)
        page.get_by_role('button',name='Сохранить в итог',exact=True).first.click()
        page.locator('#ingredients').fill('макароны')
        page.get_by_role('button',name='Подобрать блюда',exact=True).click()
        expect(page.locator('#recipe-results')).to_contain_text('Нужно добавить:')
        page.locator('#ingredients').fill('нет продуктов')
        page.get_by_role('button',name='Подобрать блюда',exact=True).click()
        expect(page.locator('#recipe-results')).to_contain_text('БЫСТРЫЕ НАБОРЫ')
        page.locator('#ingredients').fill('абракадабра')
        page.get_by_role('button',name='Подобрать блюда',exact=True).click()
        expect(page.locator('#recipe-results')).to_contain_text('Не удалось распознать: абракадабра')
        expect(page.locator('.online-results')).to_contain_text('подходящих рецептов не найдено')
        expect(page.locator('#recipe-results')).to_contain_text('БЫСТРЫЕ НАБОРЫ')
        page.locator('#ingredients').fill('курица гречка')
        page.get_by_role('button',name='Подобрать блюда',exact=True).click()
        expect(page.locator('#recipe-results')).to_contain_text('Курица с гречкой')
        page.get_by_role('button',name='Подобрать занятия',exact=True).click()
        page.get_by_role('button',name='Подобрать',exact=True).click()
        assert 'онлайн-сопровождение' in page.locator('#result').inner_text()
        assert page.locator('select').count()==0
        page.get_by_role('button',name='Заявка и запись',exact=True).click()
        page.locator('[name=name]').fill('Тест')
        page.locator('[name=message]').fill('<script>alert(1)</script>')
        page.locator('[name=consent]').check()
        page.get_by_role('button',name='Подготовить обращение',exact=True).click()
        assert page.locator('#result script').count()==0
        assert 'Gym_mom1988' in page.locator('#result a').get_attribute('href')
        page.get_by_role('button',name='Итог в PDF',exact=True).click()
        expect(page.locator('#report')).to_contain_text('104 ккал')
        with page.expect_download() as download:
            page.get_by_role('button',name='Скачать PDF',exact=True).click()
        pdf=Path('qa-output') / ('afita-'+str(width)+'.pdf')
        download.value.save_as(pdf)
        text=subprocess.check_output(['pdftotext',str(pdf),'-'],text=True)
        assert '104 ккал' in text and 'Афита' in text
        page.screenshot(path='qa-output/afita-'+str(width)+'.png',full_page=True)
        page.get_by_role('button',name='Очистить итог',exact=True).click()
        assert 'Здесь пока пусто' in page.locator('#report').inner_text()
        assert page.evaluate('document.documentElement.scrollWidth<=innerWidth')
        page.get_by_role('button',name='Что приготовить',exact=True).click()
        page.locator('#ingredients').fill('чечевица')
        page.get_by_role('button',name='Подобрать блюда',exact=True).click()
        expect(page.locator('.online-results')).to_contain_text('Чечевичный суп из открытого источника')
        expect(page.locator('.online-results a').first).to_have_attribute('href','https://ru.wikibooks.org/wiki/%D0%A0%D0%B5%D1%86%D0%B5%D0%BF%D1%82:%D0%A2%D0%B5%D1%81%D1%82')
        page.get_by_role('button',name='Продукты и калории',exact=True).click()
        page.locator('#grams').fill('200')
        page.locator('#search').fill('Незнакомый продукт')
        expect(page.locator('#food-results')).to_contain_text('Тестовый продукт из интернета')
        expect(page.locator('#food-results')).to_contain_text('200 ккал')
    # Widget keeps the conversation frame alive when switching to actions.
    page.route('https://assistant.alenafit.com/**',lambda route:route.fulfill(status=200,content_type='text/html',body='<p>Тестовый чат</p>'))
    page.set_viewport_size({'width':390,'height':844})
    page.goto('http://localhost:8766/')
    page.locator('.afit-launch').click()
    panel=page.locator('.afit-window')
    expect(panel).to_be_visible()
    panel.get_by_role('button',name='Действия',exact=True).click()
    tools=page.frame_locator('iframe[title="Инструменты Афиты"]')
    expect(tools.locator('#ingredients')).to_be_visible()
    tools.get_by_role('button',name='Продукты и калории',exact=True).click()
    expect(tools.locator('#search')).to_be_visible()
    tools.locator('#search').fill('яблоко')
    tools.locator('#grams').fill('200')
    expect(tools.locator('#food-results')).to_contain_text('104 ккал')
    panel.get_by_role('button',name='Чат',exact=True).click()
    expect(page.locator('iframe[title="Чат с Афитой"]')).to_be_visible()
    panel.get_by_role('button',name='Действия',exact=True).click()
    expect(tools.locator('#search')).to_have_value('яблоко')
    page.locator('.afit-close').click()
    expect(panel).to_be_hidden()
    expect(page.locator('.afit-launch')).to_be_focused()
    assert not errors,errors
    browser.close()
print('Assistant actions: four viewport sizes, calculations, validation, recipes, format, request escaping and report OK')
