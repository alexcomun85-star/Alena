"""Редактура текстов пилота (v7). Запуск последним: python3 scripts/build_pilot_copy.py .
Принципы (навыки ux-copy и brand-review «Сила без перегибов»):
  - каждая фраза отвечает на вопрос посетителя или ведёт к действию; декоративные убираем;
  - заголовок называет, что в блоке, без игры слов, которую надо расшифровывать;
  - одно действие — одно название: везде «Написать в Telegram»;
  - без противоречий концепции (опыт Алёны — силовой спорт, поэтому «Не спорт» убрано).
"""
import re, sys, pathlib

root = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else ".")
p = root / "pilot.html"
h = p.read_text(encoding="utf-8")

def rep(old, new, count=1):
    global h
    if old not in h:
        raise SystemExit("не найдено: " + old[:90])
    h = h.replace(old, new, count)

# 1. Хэштеги-надзаголовки над разделами — рубрики канала, на сайте ничего не сообщают
h = re.sub(r'<span class="tag">#[^<]*</span>\s*', '', h)
# надзаголовок первого экрана переносим в подзаголовок (см. п. 2)
h = re.sub(r'<span class="tag">Онлайн и мини-группы в СПб</span>\s*', '', h)

# 2. Первый экран: короче, с форматом и географией; аудитория — в следующем блоке
rep('<p class="sub">Силовые тренировки с упором на технику и питание без запретов. Для тех, кто <b>возвращается в зал</b> после паузы, совмещает спорт с работой или <b>боится травм</b>.</p>',
    '<p class="sub">Силовые тренировки с упором на технику и питание без запретов. Онлайн из любого города или в мини-группе в центре Петербурга.</p>')
h = h.replace('<p class="cta-hint">Первым сообщением — слово «СТАРТ», оно подставится само.</p>\n', '')
h = h.replace('<p class="cta-hint">Первым сообщением — слово «СТАРТ», оно подставится само.</p>', '')

# 3. Заголовки разделов: называют содержание
rep('<h2>Узнали себя? <em>Вам сюда</em></h2>', '<h2>Кому <em>подойдёт</em></h2>')
rep('<h2>По блину <em>за раз</em></h2>', '<h2>Как начинаем <em>работу</em></h2>')
h = h.replace('<h2 id="demoTitle">За планом — <em>живой человек</em></h2>', '<h2 id="demoTitle">Как проходит <em>разбор техники</em></h2>')
rep('<h2>Какой формат <em>вам подойдёт?</em></h2>', '<h2>Подобрать <em>формат</em></h2>')
rep('<h2>Привет, я Алёна. <em>Технику ставлю как в спорте</em></h2>', '<h2>Привет, <em>я Алёна</em></h2>')

# 4. Пример переписки: без служебной пометки в тексте сайта
h = h.replace('<p class="lede">Так выглядит разбор техники: вы присылаете видео подхода, я отвечаю, что поправить и какой вес взять в следующий раз.</p>',
    '<p class="lede">Вы присылаете видео подхода. Я отвечаю, что поправить и какой вес взять на следующей тренировке.</p>')
h = re.sub(r'<p class="demo-label">.*?</p>', '<p class="demo-label">Пример переписки. Настоящие покажем с согласия клиентов.</p>', h, count=1, flags=re.S)

# 5. Подбор формата
rep('<p class="lede">Ответьте на 4 вопроса — и я подскажу, с чего начать. Ответы никуда не отправляются, всё остаётся у вас в браузере.</p>',
    '<p class="lede">Ответьте на 4 вопроса, и я подскажу, с чего начать. Ответы никуда не отправляются.</p>')

# 6. «Не фитнес. Не спорт. Сила для жизни.» — убрать блок: противоречит опыту Алёны в силовом спорте
h, n = re.subn(r'\s*<section class="manifest g" id="manifest">.*?</section>', '', h, count=1, flags=re.S)
if not n:
    raise SystemExit("нет блока manifest")

# 7. «Зачем тренер»: одна мысль и понятная кнопка
rep('<p class="lede">Многим хватит бесплатного. Как понять, хватит ли вам, что говорят исследования и чем отличаются три пути — сам, онлайн или в мини-группе.</p>',
    '<p class="lede">Многим хватит бесплатных материалов. Короткий тест покажет, хватит ли вам или лучше заниматься с тренером.</p>')
rep('<span class="btn btn-line pilot-btn">Читать и пройти тест</span>', '<span class="btn btn-line pilot-btn">Пройти тест</span>')

# 8. Финальный блок: убрать слоган-плашку и список «Техника / Поддержка / Ваш темп»
h = re.sub(r'<span class="invite-eyebrow">.*?</span>\s*', '', h, count=1, flags=re.S)
h = re.sub(r'<ul class="invite-values"[^>]*>.*?</ul>\s*', '', h, count=1, flags=re.S)
rep('<h2 id="inviteTitle">Сильнее —<br><em>в своём<br>темпе.</em></h2>', '<h2 id="inviteTitle">С чего <em>начать?</em></h2>')
rep('>Обсудить первый шаг <span aria-hidden="true">↗</span></a>', '>Написать в Telegram <span aria-hidden="true">↗</span></a>')
rep('<p class="invite-note">Откроется Telegram · Ответит Алёна</p>', '<p class="invite-note">Отвечаю сама, с 9 до 21 по Москве.</p>')

# 9. «СТАРТ» — кодовое слово из канала; на сайте выглядит странно. Заменяем обычными словами.
#    В Telegram подставляется фраза-приветствие: по ней же считаем заявки с сайта.
START = '%D0%A1%D0%A2%D0%90%D0%A0%D0%A2'
HELLO = '%D0%97%D0%B4%D1%80%D0%B0%D0%B2%D1%81%D1%82%D0%B2%D1%83%D0%B9%D1%82%D0%B5%2C%20%D0%90%D0%BB%D1%91%D0%BD%D0%B0%21%20%D0%A5%D0%BE%D1%87%D1%83%20%D0%BD%D0%B0%D1%87%D0%B0%D1%82%D1%8C%20%D1%82%D1%80%D0%B5%D0%BD%D0%B8%D1%80%D0%BE%D0%B2%D0%B0%D1%82%D1%8C%D1%81%D1%8F'
h = h.replace('?text=' + START, '?text=' + HELLO)
rep('rel="noopener">СТАРТ</a>', 'rel="noopener">Написать</a>')
rep('Пишете «СТАРТ» в Telegram</b><span>Можно одним словом, остальное спрошу сама.',
    'Пишете мне в Telegram</b><span>Одного сообщения достаточно, остальное спрошу сама.')
h = h.replace('От «СТАРТ» до первой тренировки', 'От первого сообщения до тренировки')
rep('<b>Первый шаг — «СТАРТ»</b><span>Напишите в Telegram, подберу формат', '<b>Первый шаг</b><span>Напишите в Telegram, подберу формат')
h = h.replace('место бронируется через «СТАРТ» в Telegram', 'место бронируется сообщением в Telegram')
if 'СТАРТ' in h.replace(START, ''):
    raise SystemExit('осталось слово СТАРТ')

# 10. Регалии на первом экране: были «таблетками», похожими на кнопки. Делаем одну строку текста
h, n = re.subn(r'<p class="trust-line">.*?</p>',
    '<p class="trust-line">Инструктор групповых программ (КОРУС), спортивный нутрициолог, бронза WRPF в становой тяге.</p>', h, count=1, flags=re.S)
if not n:
    raise SystemExit('нет строки регалий')

# 11. Логика страницы: порядок блоков = путь решения посетителя
#     первый экран → кому подойдёт / не подойдёт → как начинаем → как выглядит разбор →
#     форматы и цены → подобрать формат → обо мне → бесплатные инструменты → «зачем тренер» →
#     исследования → вопросы → контакт
def cut(sec_id):
    global h
    m = re.search(r'[ \t]*<section[^>]*\bid="%s"[^>]*>.*?</section>\n?' % re.escape(sec_id), h, re.S)
    if not m:
        raise SystemExit('нет секции ' + sec_id)
    h = h[:m.start()] + h[m.end():]
    return m.group(0)
def insert_after(sec_id, block):
    global h
    m = re.search(r'<section[^>]*\bid="%s"[^>]*>.*?</section>\n?' % re.escape(sec_id), h, re.S)
    h = h[:m.end()] + block + h[m.end():]
insert_after('who', cut('limits'))          # «кому не подойдёт» — сразу за «кому подойдёт»
insert_after('tools', cut('zachem'))        # «зачем тренер, если всё есть на сайте» — после того, как показали, что есть на сайте
rep('<h2>Кому формат <em>не подойдёт</em></h2>', '<h2>Кому <em>не подойдёт</em></h2>')

# 12. Повторы: 105 кг было 4 раза (подзаголовок, текст, крупная цифра, дипломы) — крупную цифру убираем
h = re.sub(r'<div class="about-stat">.*?</div>\s*', '', h, count=1, flags=re.S)
# кнопка «Форматы и цены» в блоке переписки ведёт на соседний блок ниже — лишняя
h = h.replace('\n    <a class="btn btn-line" href="#plans">Форматы и цены</a>', '', 1)

# 13. Исследования — одна строка со ссылками
h, n = re.subn(r'(<section class="g pilot-science" id="research">\s*<div class="w">).*?(</div>\s*</section>)',
    lambda m: m.group(1) + '\n      <p><b>Подход опирается на исследования.</b> Разборы простым языком — <a href="nauka.html">на сайте</a> и <a href="https://t.me/alena_gymmom" target="_blank" rel="noopener">в канале</a>.</p>\n    ' + m.group(2),
    h, count=1, flags=re.S)
if not n:
    raise SystemExit('нет блока исследований')
# подвал: кнопка «Написать в Telegram» стоит сразу под такой же кнопкой финального блока — убираем
h = re.sub(r'(<div class="pf-top">.*?)<a class="btn btn-main"[^>]*>Написать в Telegram</a>', r'\1', h, count=1, flags=re.S)

# 14. Подвал: ссылка на удалённый блок не нужна; меню ссылалось на #creds — блок остаётся
p.write_text(h, encoding="utf-8")
print("copy ok", len(h))
